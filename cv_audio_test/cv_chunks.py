def find_index_fuzzy(words, seq, use_end=False, max_gap=3):
    for i in range(len(words)):
        w_idx = i
        s_idx = 0
        matched = []
        while s_idx < len(seq) and w_idx < len(words):
            if match_word(words[w_idx], seq[s_idx]):
                matched.append(w_idx)
                s_idx += 1
            w_idx += 1
            if matched and w_idx - matched[-1] > max_gap + 1:
                break
        if s_idx == len(seq):
            return matched[-1] if use_end else matched[0]
    return None

def normalize_subject_id(name_or_path):
    base = os.path.splitext(os.path.basename(str(name_or_path)))[0]
    if base.endswith("_transcript"):
        base = base[: -len("_transcript")]
    return base

def build_annotation_map(dirs_by_group):
    ann_map = {}
    for _, folder in dirs_by_group.items():
        if not Path(folder).exists():
            continue
        for f in os.listdir(folder):
            if f.lower().endswith(".csv"):
                sid = normalize_subject_id(f)
                ann_map[sid] = os.path.join(folder, f)
    return ann_map

def build_video_and_group_maps(dirs_by_group):
    vid_map, group_map = {}, {}
    for group_name, folder in dirs_by_group.items():
        if not Path(folder).exists():
            continue
        for f in os.listdir(folder):
            if f.lower().endswith((".mp4", ".mov", ".avi", ".mkv")):
                sid = normalize_subject_id(f)
                vid_map[sid] = os.path.join(folder, f)
                group_map[sid] = group_name  # "control" or "experimental"
    return vid_map, group_map


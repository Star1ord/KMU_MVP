def find_passage_timestamps(df, alternatives):
    """
    Try all alternatives: each has start_phrase and end_phrase.
    Returns (start_time, end_time) of first matching alternative.
    """
    for alt in alternatives:
        start_time = find_phrase_fuzzy(df, alt["start_phrase"], return_end=False)
        if start_time is None:
            continue
        end_time   = find_phrase_fuzzy(df, alt["end_phrase"], return_end=True)
        if end_time is None:
            continue
        return start_time, end_time
    return None, None

def find_phrase_fuzzy(df, phrase_seq, return_end=False, max_gap=3):
    """
    Finds the first fuzzy match for phrase_seq in df['text'].
    Allows noise words between matches (max_gap controls the allowed distance).

    return_end=False → returns start_time of the first matched word
    return_end=True  → returns end_time of the last matched word
    """
    words = df["text"].tolist()

    for i in range(len(words)):
        w_idx = i
        s_idx = 0
        matched_indices = []

        while s_idx < len(phrase_seq) and w_idx < len(words):
            if match_word(words[w_idx], phrase_seq[s_idx]):
                matched_indices.append(w_idx)
                s_idx += 1
            w_idx += 1

            # too big a gap since last matched word → stop
            if matched_indices and w_idx - matched_indices[-1] > max_gap + 1:
                break

        if s_idx == len(phrase_seq):  # found a complete sequence
            if return_end:
                return df.iloc[matched_indices[-1]]["end_time"]
            else:
                return df.iloc[matched_indices[0]]["start_time"]

    return None


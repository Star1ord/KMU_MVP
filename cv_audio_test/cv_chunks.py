def process_group(video_dir: Path, csv_dir: Path, group_name: str):
    for csv_file in csv_dir.glob("*.csv"):
        # Extract subject base name without "_transcript"
        subject_base = csv_file.stem.replace("_transcript", "")

        # Try to find matching video
        video_file = next(video_dir.glob(f"{subject_base}.mp4"), None)
        if not video_file:
            print(f"⚠ No video found for {subject_base} in {group_name}")
            continue

        # Load and clean transcription
        df = pd.read_csv(csv_file)
        if not {"text", "start_time", "end_time"}.issubset(df.columns):
            print(f"⚠ Invalid CSV format: {csv_file}")
            continue

        df["text"] = df["text"].astype(str).apply(clean_text)

        # Load video
        video = VideoFileClip(str(video_file))
        print(f"🎬 Processing {subject_base} ({group_name})")

        # Output subject dir
        subject_out_dir = OUTPUT_DIR / group_name / subject_base
        subject_out_dir.mkdir(parents=True, exist_ok=True)

        # Extract passages
        for passage in passages:
            # start_time, end_time = find_passage_timestamps(df, passage["start_phrase"], passage["end_phrase"])
            start_time, end_time = find_passage_timestamps(df, passage["alternatives"])
            if start_time is None or end_time is None:
                print(f"  ⏩ Skipping {passage['name']} (not found)")
                continue

            if end_time > video.duration:
                print(f"  ⚠ End time exceeds duration for {passage['name']} → clamped")
                end_time = video.duration

            print(f"  ✂ Trimming {passage['name']}: {start_time:.2f} - {end_time:.2f}")
            try:
                trimmed = video.subclip(start_time, end_time)
                passage_dir = subject_out_dir / passage["name"]
                passage_dir.mkdir(parents=True, exist_ok=True)

                s_fmt = f"{start_time:.2f}".replace('.', '_')
                e_fmt = f"{end_time:.2f}".replace('.', '_')

                output_filename = f"{passage['name']}_{s_fmt}_{e_fmt}.mp4"
                final_path = passage_dir / output_filename

                # write first to local tmp to avoid drive I/O issues
                temp_path = Path("/tmp") / output_filename

                try:
                    trimmed.write_videofile(
                        str(temp_path),
                        codec="libx264",
                        audio_codec="aac",
                        fps=video.fps,
                        ffmpeg_params=["-movflags", "+faststart"],
                        verbose=False,
                        logger=None
                    )
                    shutil.move(str(temp_path), str(final_path))
                    print(f"  ✅ Saved {final_path}")

                except Exception as e:
                    print(f"  ❌ Failed to trim {passage['name']}: {e}")

                finally:
                    if temp_path.exists():
                        try:
                            temp_path.unlink()
                        except Exception:
                            pass

            except Exception as e:
                print(f"  ❌ Failed processing passage {passage['name']}: {e}")

        video.close()


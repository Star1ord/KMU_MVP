def match_sequence(words, seq, start_idx):
    """
    Checks if seq matches words starting from start_idx.
    seq may contain strings or lists of alternative strings.
    """
    if start_idx + len(seq) > len(words):
        return False
    for i, token in enumerate(seq):
        word = words[start_idx + i]
        if isinstance(token, list):
            if word not in token:
                return False
        else:
            if word != token:
                return False
    return True

def match_word(word, target):
    """
    Returns True if the word matches the target.
    target can be a string or a list of alternative strings.
    Case-insensitive.
    """
    word = str(word).strip().lower()

    if isinstance(target, list):
        return word in [str(t).strip().lower() for t in target]
    else:
        return word == str(target).strip().lower()



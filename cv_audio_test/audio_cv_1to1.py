    # segment_index is 1-based: first chunk -> frames [0:chunk_dur], second -> [chunk_dur:2*chunk_dur], etc.
    chunk_start = (seg_idx - 1) * chunk_dur
    # clamp start to reasonable range: prefer exact chunk but if start is beyond passage, snap to last chunk window
    if chunk_start >= video_len:
        # place chunk at the tail of the passage (take last chunk_dur seconds)
        chunk_start = max(0, video_len - chunk_dur)
    chunk_end = min(chunk_start + chunk_dur, video_len)

    if chunk_end <= chunk_start:
        skipped_zero_len += 1
        continue

    video_chunk = video_arr[chunk_start:chunk_end]

def label_to_group(label_str):
    if pd.isna(label_str):
        return None
    s = str(label_str).lower()
    if "control" in s or "negative" in s:
        return "control"
    if "positive" in s or "experimental" in s:
        return "experimental"
    return "control" if "control" in s else "experimental"

def subject_key_candidates(pid):
    # raw
    if pd.isna(pid):
        return []
    pid = str(pid).strip()
    cands = []
    cands.append(pid)
    cands.append(pid.replace("-", "_"))
    cands.append(pid.replace("-", "."))
    cands.append(pid.replace("_", "."))
    cands.append(pid.replace(".", "_"))
    no_paren = re.sub(r"\(.*?\)", "", pid).strip()
    cands.append(no_paren)
    cands.append(no_paren.replace("-", "_"))
    cands.append(no_paren.replace(".", "_"))
    def collapse(s):
        s = re.sub(r'[_\.\-]{2,}', '_', s)
        s = s.strip("_.- ")
        return s
    cands = [collapse(x) for x in cands if x]
    seen = set()
    out = []
    for x in cands:
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out

def find_subject_in_group(group_dict, pid):
    for cand in subject_key_candidates(pid):
        if cand in group_dict:
            return cand
    return None


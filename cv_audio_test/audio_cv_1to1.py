    def __init__(self, input_dim, dropout=0.3):
        super().__init__()

        # Funnel-shaped architecture: widen → narrow
        hidden_dims = [
            input_dim // 2,
            input_dim,
            input_dim * 2,
            input_dim,
            max(64, input_dim // 2)
        ]

